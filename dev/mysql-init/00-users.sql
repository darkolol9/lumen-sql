SET NAMES utf8mb4;
CREATE DATABASE IF NOT EXISTS shop;
CREATE DATABASE IF NOT EXISTS saas;
CREATE DATABASE IF NOT EXISTS hr;

CREATE USER IF NOT EXISTS 'lumen'@'%' IDENTIFIED BY 'lumen';
GRANT ALL PRIVILEGES ON shop.* TO 'lumen'@'%';
GRANT ALL PRIVILEGES ON saas.* TO 'lumen'@'%';
GRANT ALL PRIVILEGES ON hr.* TO 'lumen'@'%';

CREATE USER IF NOT EXISTS 'reader'@'%' IDENTIFIED BY 'reader';
GRANT SELECT, SHOW VIEW ON shop.* TO 'reader'@'%';
GRANT SELECT, SHOW VIEW ON saas.* TO 'reader'@'%';
GRANT SELECT, SHOW VIEW ON hr.* TO 'reader'@'%';
FLUSH PRIVILEGES;
